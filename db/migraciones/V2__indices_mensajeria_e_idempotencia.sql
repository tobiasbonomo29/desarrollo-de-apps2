-- =============================================================================
--  MediConecta - V2: indices, avisos de la mensajeria e idempotencia
-- =============================================================================
--
--  * Indices para las consultas que hace la aplicacion. Usan IF NOT EXISTS
--    porque una base creada a mano con el viejo scripts/db/esquema.sql ya
--    podia tenerlos.
--  * notificaciones: lo que generan los consumidores JMS. La restriccion unica
--    (evento_id, tipo) hace idempotente al consumidor.
--  * mensajes_fallidos: lo que llega a la cola de mensajes muertos (DLQ).
--  * claves_idempotencia: Idempotency-Key de POST /api/turnos.
-- =============================================================================

CREATE INDEX IF NOT EXISTS ix_turnos_fecha       ON turnos (fecha_hora);
CREATE INDEX IF NOT EXISTS ix_turnos_profesional ON turnos (profesional_id, fecha_hora);
CREATE INDEX IF NOT EXISTS ix_turnos_paciente    ON turnos (paciente_id);
CREATE INDEX IF NOT EXISTS ix_disp_profesional   ON disponibilidades (profesional_id);

CREATE TABLE notificaciones (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_id       VARCHAR(60)  NOT NULL,
    tipo            VARCHAR(30)  NOT NULL,
    canal           VARCHAR(20)  NOT NULL,
    turno_id        BIGINT       NOT NULL,
    destinatario    VARCHAR(120) NOT NULL,
    mensaje         VARCHAR(500) NOT NULL,
    creada_en       TIMESTAMP(6) NOT NULL,
    programada_para TIMESTAMP(6),
    CONSTRAINT uk_notificaciones_evento_tipo UNIQUE (evento_id, tipo),
    CONSTRAINT notificaciones_tipo_check  CHECK (tipo IN ('CONFIRMACION', 'RECORDATORIO', 'AVISO_PROFESIONAL')),
    CONSTRAINT notificaciones_canal_check CHECK (canal IN ('EMAIL', 'SMS', 'AGENDA')),
    CONSTRAINT fk_notificaciones_turno FOREIGN KEY (turno_id) REFERENCES turnos (id)
);

CREATE INDEX ix_notificaciones_turno ON notificaciones (turno_id);

COMMENT ON TABLE notificaciones IS 'Avisos generados por los consumidores JMS del evento TURNO_CONFIRMADO.';

CREATE TABLE mensajes_fallidos (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mensaje_id       VARCHAR(120)  NOT NULL,
    evento_id        VARCHAR(60),
    destino_original VARCHAR(200),
    cuerpo           VARCHAR(2000),
    recibido_en      TIMESTAMP(6)  NOT NULL,
    CONSTRAINT uk_mensajes_fallidos_mensaje UNIQUE (mensaje_id)
);

COMMENT ON TABLE mensajes_fallidos IS 'Mensajes JMS que agotaron los reintentos y llegaron a la DLQ MensajesFallidos.';

CREATE TABLE claves_idempotencia (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clave     VARCHAR(100) NOT NULL,
    usuario   VARCHAR(60)  NOT NULL,
    huella    VARCHAR(64)  NOT NULL,
    turno_id  BIGINT       NOT NULL,
    creada_en TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_claves_idempotencia_usuario_clave UNIQUE (usuario, clave),
    CONSTRAINT fk_claves_idempotencia_turno FOREIGN KEY (turno_id) REFERENCES turnos (id)
);

CREATE INDEX ix_claves_idempotencia_creada ON claves_idempotencia (creada_en);

COMMENT ON TABLE claves_idempotencia IS 'Idempotency-Key ya procesadas en POST /api/turnos (vigencia 24 h).';
