-- =============================================================================
--  MediConecta - V1: esquema inicial (Entregas 1 y 2)
-- =============================================================================
--
--  Es exactamente el esquema que generaba Hibernate con hbm2ddl.auto=update
--  hasta la Entrega 2 (mismos tipos, columnas identity, unicos y claves
--  foraneas). Por eso las bases que ya existian no lo vuelven a ejecutar:
--  Flyway las toma como "version 1" (baselineOnMigrate) y solo les aplica las
--  migraciones siguientes. Una base vacia lo ejecuta y queda igual.
--
--  Regla: una migracion ya publicada NO se modifica nunca (Flyway guarda su
--  checksum y se niega a seguir si cambia). Todo cambio va en un V<n> nuevo.
-- =============================================================================

CREATE TABLE pacientes (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activo     BOOLEAN      NOT NULL,
    cobertura  VARCHAR(60),
    documento  VARCHAR(20)  NOT NULL,
    email      VARCHAR(120),
    nombre     VARCHAR(120) NOT NULL,
    telefono   VARCHAR(40),
    usuario    VARCHAR(60),
    CONSTRAINT uk_pacientes_documento UNIQUE (documento)
);

COMMENT ON COLUMN pacientes.documento IS 'Clave de negocio: es lo que identifica al paciente en las URLs de la API.';
COMMENT ON COLUMN pacientes.usuario   IS 'Usuario asociado; permite que un rol PACIENTE vea solo su propia ficha.';

CREATE TABLE profesionales (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activo       BOOLEAN      NOT NULL,
    email        VARCHAR(120),
    especialidad VARCHAR(80)  NOT NULL,
    matricula    VARCHAR(30)  NOT NULL,
    nombre       VARCHAR(120) NOT NULL,
    usuario      VARCHAR(60),
    CONSTRAINT uk_profesionales_matricula UNIQUE (matricula),
    CONSTRAINT uk_profesionales_usuario   UNIQUE (usuario)
);

COMMENT ON COLUMN profesionales.usuario IS 'Usuario asociado; permite que un rol MEDICO administre solo su propia disponibilidad.';

CREATE TABLE disponibilidades (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dia_semana       VARCHAR(12) NOT NULL,
    duracion_minutos INTEGER     NOT NULL,
    hora_desde       TIME(6)     NOT NULL,
    hora_hasta       TIME(6)     NOT NULL,
    profesional_id   BIGINT      NOT NULL,
    CONSTRAINT disponibilidades_dia_semana_check CHECK (dia_semana IN
        ('MONDAY', 'TUESDAY', 'WEDNESDAY', 'THURSDAY', 'FRIDAY', 'SATURDAY', 'SUNDAY')),
    CONSTRAINT fk_disponibilidades_profesional FOREIGN KEY (profesional_id) REFERENCES profesionales (id)
);

COMMENT ON TABLE disponibilidades IS 'Franjas semanales de atencion. De aca sale la grilla de horarios que se ofrece al paciente.';

CREATE TABLE turnos (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    archivado      BOOLEAN      NOT NULL,
    especialidad   VARCHAR(80)  NOT NULL,
    estado         VARCHAR(20)  NOT NULL,
    fecha_hora     TIMESTAMP(6) NOT NULL,
    motivo         VARCHAR(200),
    paciente_id    BIGINT       NOT NULL,
    profesional_id BIGINT       NOT NULL,
    CONSTRAINT turnos_estado_check CHECK (estado IN ('PROGRAMADO', 'ATENDIDO', 'CANCELADO')),
    CONSTRAINT fk_turnos_paciente    FOREIGN KEY (paciente_id)    REFERENCES pacientes (id),
    CONSTRAINT fk_turnos_profesional FOREIGN KEY (profesional_id) REFERENCES profesionales (id)
);

COMMENT ON COLUMN turnos.estado IS 'PROGRAMADO, ATENDIDO o CANCELADO. Lo cambian solo las clases del patron State.';
COMMENT ON COLUMN turnos.archivado IS 'Archivado logico: solo un turno CANCELADO se puede archivar. Sigue en el historial del paciente.';

-- Usuarios (Entrega 2): autenticacion con JWT. La contrasena se guarda como
-- hash PBKDF2 (pbkdf2$iteraciones$sal$hash), nunca en claro.
CREATE TABLE usuarios (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activo      BOOLEAN      NOT NULL,
    hash_clave  VARCHAR(200) NOT NULL,
    usuario     VARCHAR(60)  NOT NULL,
    CONSTRAINT uk_usuarios_usuario UNIQUE (usuario)
);

CREATE TABLE usuario_roles (
    usuario_id  BIGINT      NOT NULL,
    rol         VARCHAR(20) NOT NULL,
    CONSTRAINT usuario_roles_pkey PRIMARY KEY (usuario_id, rol),
    CONSTRAINT fk_usuario_roles_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id)
);
